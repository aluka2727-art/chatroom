import os
import re
import sqlite3
from pathlib import Path


def load_env_file():
    path = Path(__file__).resolve().parent / ".env"
    if not path.is_file():
        return
    for raw_line in path.read_text().splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        os.environ.setdefault(key.strip(), value.strip().strip('"').strip("'"))


class MappingRow(dict):
    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return dict.__getitem__(self, key)


class Result:
    def __init__(self, rows):
        self._rows = rows

    def fetchone(self):
        return self._rows[0] if self._rows else None

    def fetchall(self):
        return self._rows

    def close(self):
        return None


def translate_postgres(sql):
    sql = re.sub(
        r"(?P<col>(?:\w+\.)?username)\s*=\s*(?P<value>'(?:''|[^'])*'|\?)\s+COLLATE\s+NOCASE",
        lambda match: f"LOWER({match.group('col')}) = LOWER({match.group('value')})",
        sql,
        flags=re.IGNORECASE,
    )
    sql = re.sub(
        r"(?P<col>(?:\w+\.)?username)\s+COLLATE\s+NOCASE",
        lambda match: f"LOWER({match.group('col')})",
        sql,
        flags=re.IGNORECASE,
    )
    sql = sql.replace("BEGIN IMMEDIATE", "BEGIN")
    sql = re.sub(
        r"strftime\('%Y-%m-%dT%H:%M:%fZ',\s*'now'\)",
        "to_char(timezone('utc', clock_timestamp()), 'YYYY-MM-DD\"T\"HH24:MI:SS.MS\"Z\"')",
        sql,
    )
    return sql.replace("?", "%s")


class PostgresConnection:
    def __init__(self, url):
        import psycopg
        from psycopg.rows import dict_row

        if "sslmode=" not in url:
            url += "&sslmode=require" if "?" in url else "?sslmode=require"
        self.raw = psycopg.connect(url, row_factory=dict_row)

    def execute(self, sql, params=None):
        if sql.strip().upper() in {"BEGIN", "BEGIN IMMEDIATE"}:
            return Result([])
        with self.raw.cursor() as cursor:
            cursor.execute(translate_postgres(sql), params or ())
            if cursor.description is None:
                return Result([])
            return Result([MappingRow(dict(row)) for row in cursor.fetchall()])

    def executemany(self, sql, seq):
        with self.raw.cursor() as cursor:
            cursor.executemany(translate_postgres(sql), list(seq))
        return Result([])

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        self.raw.close()


