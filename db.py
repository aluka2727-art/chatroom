def copy_sqlite_to_postgres(connection, sqlite_path):
    source = sqlite3.connect(sqlite_path)
    source.row_factory = sqlite3.Row
    try:
        connection.execute("ALTER TABLE messages DISABLE TRIGGER USER")
        connection.execute(
            """
            TRUNCATE TABLE
                push_presence,
                chat_reads,
                dm_reads,
                account_warnings,
                push_subscriptions,
                direct_messages,
                message_events,
                messages,
                deleted_accounts,
                accounts
            RESTART IDENTITY CASCADE
            """
        )
        accounts = source.execute(
            "SELECT id, username, password_hash, role, created_at FROM accounts ORDER BY id"
        ).fetchall()
        for row in accounts:
            connection.execute(
                """
                INSERT INTO accounts (id, username, password_hash, role, created_at)
                VALUES (?, ?, ?, ?, ?)
                """,
                (row["id"], row["username"], row["password_hash"], row["role"], row["created_at"]),
            )
        for row in source.execute(
            "SELECT account_id, username, deleted_at FROM deleted_accounts"
        ):
            connection.execute(
                "INSERT INTO deleted_accounts (account_id, username, deleted_at) VALUES (?, ?, ?)",
                (row["account_id"], row["username"], row["deleted_at"]),
            )
        messages = source.execute(
            "SELECT id, author_id, body, is_deleted, reply_to_id, created_at FROM messages ORDER BY id"
        ).fetchall()
        for row in messages:
            connection.execute(
                """
                INSERT INTO messages (id, author_id, body, is_deleted, reply_to_id, created_at)
                VALUES (?, ?, ?, ?, NULL, ?)
                """,
                (row["id"], row["author_id"], row["body"], row["is_deleted"], row["created_at"]),
            )
        for row in messages:
            if row["reply_to_id"] is not None:
                connection.execute(
                    "UPDATE messages SET reply_to_id = ? WHERE id = ?",
                    (row["reply_to_id"], row["id"]),
                )
        direct_messages = source.execute(
            """
            SELECT id, sender_id, recipient_id, body, reply_to_id, created_at
            FROM direct_messages ORDER BY id
            """
        ).fetchall()
        for row in direct_messages:
            connection.execute(
                """
                INSERT INTO direct_messages
                    (id, sender_id, recipient_id, body, reply_to_id, created_at)
                VALUES (?, ?, ?, ?, NULL, ?)
                """,
                (row["id"], row["sender_id"], row["recipient_id"], row["body"], row["created_at"]),
            )
        for row in direct_messages:
            if row["reply_to_id"] is not None:
                connection.execute(
                    "UPDATE direct_messages SET reply_to_id = ? WHERE id = ?",
                    (row["reply_to_id"], row["id"]),
                )
        table_names = {
            row["name"]
            for row in source.execute("SELECT name FROM sqlite_master WHERE type = 'table'")
        }
        if "chat_reads" in table_names:
            for row in source.execute(
                "SELECT account_id, last_read_message_id FROM chat_reads ORDER BY account_id"
            ):
                connection.execute(
                    "INSERT INTO chat_reads (account_id, last_read_message_id) VALUES (?, ?)",
                    (row["account_id"], row["last_read_message_id"]),
                )
        if "dm_reads" in table_names:
            for row in source.execute(
                """
                SELECT account_id, partner_id, last_read_message_id
                FROM dm_reads ORDER BY account_id, partner_id
                """
            ):
                connection.execute(
                    """
                    INSERT INTO dm_reads (account_id, partner_id, last_read_message_id)
                    VALUES (?, ?, ?)
                    """,
                    (row["account_id"], row["partner_id"], row["last_read_message_id"]),
                )
        for row in source.execute(
            "SELECT id, account_id, endpoint, p256dh, auth, created_at FROM push_subscriptions ORDER BY id"
        ):
            connection.execute(
                """
                INSERT INTO push_subscriptions (id, account_id, endpoint, p256dh, auth, created_at)
                VALUES (?, ?, ?, ?, ?, ?)
                """,
                (row["id"], row["account_id"], row["endpoint"], row["p256dh"], row["auth"], row["created_at"]),
            )
        for row in source.execute(
            "SELECT id, account_id, message_id, seen_at, created_at FROM account_warnings ORDER BY id"
        ):
            connection.execute(
                """
                INSERT INTO account_warnings (id, account_id, message_id, seen_at, created_at)
                VALUES (?, ?, ?, ?, ?)
                """,
                (row["id"], row["account_id"], row["message_id"], row["seen_at"], row["created_at"]),
            )
        for row in source.execute("SELECT id, message_id FROM message_events ORDER BY id"):
            connection.execute(
                "INSERT INTO message_events (id, message_id) VALUES (?, ?)",
                (row["id"], row["message_id"]),
            )
        for table in (
            "accounts",
            "messages",
            "direct_messages",
            "push_subscriptions",
            "message_events",
            "account_warnings",
        ):
            connection.execute(
                f"""
                SELECT setval(
                    pg_get_serial_sequence('{table}', 'id'),
                    GREATEST(COALESCE((SELECT MAX(id) FROM {table}), 1), 1),
                    (SELECT COUNT(*) > 0 FROM {table})
                )
                """
            )
        connection.execute("ALTER TABLE messages ENABLE TRIGGER USER")
        connection.commit()
        return {
            "accounts": len(accounts),
            "messages": len(messages),
            "direct_messages": len(direct_messages),
        }
    except Exception:
        connection.rollback()
        raise
    finally:
        source.close()
